-- Emerald support for Dialogue Portraits (Gen 3).
--
-- ---- why this file exists, and why it is a separate tree
--
-- Everything else in this repository is FireRed / LeafGreen.  The mod's own
-- header says so, and every data table it ships -- art/trainer_ids.lua,
-- art/map_art.lua, art/crops.lua, the GFX_ART / SPRITE_ART tables in main.lua --
-- is keyed to facts that only exist IN THOSE TWO CARTS:
--
--   * the ScriptKey `g3:XXXXXXXX` the FRLG importer stamps on every map object;
--   * the FRLG graphics-id space (GFX_ART[25] = 103, and so on);
--   * the FRLG map-id spelling (FR_ROUTE_24, ...);
--   * the FRLG trainer CLASS vs trainer PIC number spaces, which are two
--     different spaces in FRLG and a third, different thing in Emerald;
--   * the 240x160 FireRed message box and the FireRed latin_normal font, both
--     of which the mod's seams (src.ui.game3.message / chrome / frlg_font) are.
--
-- Pokemon Emerald is a Gen 3 game, but it is NOT a FireRed variant: its ROM
-- layout, its script bytecode addresses, its trainer table, its overworld
-- graphics ids, its map ids and its dialogue box all differ.  A "support" that
-- pointed the FRLG tables at an Emerald cart would not be support -- it would
-- be a wrong answer wearing the right shape, which is the exact failure the
-- brief forbids ("Emerald data must not be mistaken for FRLG data").
--
-- So Emerald gets its own namespace, its own detection, its own data table and
-- its own resolver, and FRLG keeps every byte of the behaviour it had.  Nothing
-- in this file is reachable from an FRLG boot: the caller in main.lua resolves
-- the game first and only calls in here when the answer is Emerald.
--
-- ---- what THIS build actually supports, stated honestly
--
-- The engine ships an Emerald import path, so an Emerald boot reaches a mod
-- with real Emerald data.  This module walks that data the same way the FRLG
-- side walks its own, but off its OWN tables:
--
--   emerald/trainer_ids.lua   Emerald scriptKey -> Emerald trainer id
--   emerald/gfx_art.lua       Emerald graphics id -> the picture it means
--   emerald/map_art.lua       (Emerald map id, graphics id) -> the picture
--   emerald/gfx_names.lua     Emerald graphics id -> the cart's name for it
--   the engine's trainer pack  trainer id -> class, name and picture
--   the engine's trainer pics  picture number -> the 64x64 portrait
--
-- The first four are generated by .probe/dp3_emit_emerald_*.lua from the
-- engine's own Emerald extraction of the player's ROM; the last two come from
-- the engine, read through the same `src.core.game3` services the FRLG path
-- uses.  The picture, once found, is handed back in exactly the shape main.lua's
-- picArt returns, so the draw code does not know or care which game it came from.
--
-- ---- the four routes, and their order (the FRLG cascade, in Emerald dress)
--
-- The FIRST build of this module (1.3.2) implemented only route 1, and the
-- report was exactly what that predicts: "the mod loads, but not working. no
-- portraits has been showing during dialogue boxs."  Of the 2,941 objects the
-- engine places in Emerald only 588 are trainers an id can name, so 2,353
-- ordinary people resolved to nil and the caller drew a bare box.  The routes
-- are the same cascade main.lua runs for FRLG, made from Emerald facts:
--
--   1. the OBJECT's scriptKey names a TRAINER  -> that trainer's own picture.
--      Exact, and it outranks everything: an id is a person, a graphic is a
--      uniform (see emerald/trainer_ids.lua and gfx_art.lua's header).
--   2. the NAME the box says is a trainer's own name -> that trainer's picture.
--      Refused when two pictures share the name, so a generic "GRUNT" cannot
--      hand every grunt the admin's face -- the same rule as FRLG's picForName.
--   3. the object's own CLASS -> the class's picture.  Read off the object's
--      graphic's cart name, so it answers only when that name IS a class name.
--   4. the HAND-AUTHORED person table (emerald/gfx_art_people.lua): an exact
--      picture for a graphic no trainer wears, or a deliberate decline.  Runs
--      before the two statistical tables because a decision about this graphic
--      beats a majority over the ROM.
--   5. the (MAP, GRAPHIC) pair -> the picture the majority of THIS map's
--      trainers wearing that graphic have (emerald/map_art.lua).
--   6. the GRAPHIC alone -> the picture the majority of the whole ROM's
--      trainers wearing it have (emerald/gfx_art.lua).
--
-- Routes 5 and 6 are the ones that matter for the report, because the two and a
-- half thousand ordinary people have neither an id nor a name: their graphic is
-- the only fact about them, and it is what the cart dressed them in.  Route 4 is
-- what answers the people not one trainer wears -- the townsfolk, the nurse, the
-- gym leaders -- and what declines, honestly, the few the cart never drew.
--
-- ---- what is deliberately NOT here, and why it is not a gap
--
--   * no Emerald crop table.  art/crops.lua's framings are keyed to FRLG picture
--     numbers.  The engine's own `TrainerPic.front` already returns the cart's
--     picture at its own size, and main.lua's draw path frames whatever it is
--     handed, so the picture is used as the cart cut it.
--   * no Emerald CLASS-to-picture table of the FRLG kind, and no FRLG table used
--     as if it were an Emerald one.  Every table this module reads for an
--     Emerald answer is an Emerald table keyed by Emerald facts, and the
--     resolver still refuses on a non-Emerald boot by default.  A wrong face is
--     worse than none.  (1.3.3 adds a LAST-resort BORROW of a FireRed bust for
--     the few graphics Emerald has no bust for at all -- see route 7 below and
--     emerald/frlg_share.lua.  It is keyed by the Emerald GRAPHIC, never by an
--     id, because the two carts' id spaces disagree; it runs last, so it cannot
--     overrule a single Emerald answer; and it is off unless FireRed has been
--     imported.  It is a borrowing of art, not a conflation of data.)
--
-- The gap that REMAINS, stated rather than pretended away: Emerald's overworld
-- art is a SEPARATE set from its trainer busts, so a graphic worn by no trainer
-- (and named by no class) has no measured answer and gets NO portrait -- which
-- is this mod's rule everywhere the data does not decide.  Routes 4 and 5 cover
-- 69 of the 166 used person graphics; of the rest, the 13 kinds FireRed also drew
-- are borrowed by route 7, and the anonymous remainder still gets nothing.
-- Tests in tests/dp3_emerald_test.lua pin the contract either way: the resolver
-- declines with a non-empty, Emerald-naming reason rather than ever raising,
-- and it never answers an Emerald speaker from an FRLG DATA table.

local Emerald = {}

-- ---- injected dependencies
--
-- A mod's files are loaded with `load()` inside the mod's sandbox, where the
-- ambient `require` may or may not be the engine's.  Rather than guess, the
-- caller in main.lua hands this module a `require`, a mod reader and a logger
-- once, and the module uses those.  All are optional: with none, every route
-- that needs the engine reports "unknown", which is the safe answer -- unknown
-- is not Emerald, and not Emerald is not FireRed.
--
-- `Emerald.bind{ require = ..., log = ..., read = ... }` is called by main.lua
-- right after the chunk loads.  It is idempotent, so a double call is harmless.
local _require = nil
local _log = nil
local _read = nil
local _image = nil

function Emerald.bind(opts)
  opts = opts or {}
  if type(opts.require) == "function" then _require = opts.require end
  if type(opts.log) == "table" and type(opts.log.info) == "function" then
    _log = opts.log
  end
  if type(opts.read) == "function" then _read = opts.read end
  if type(opts.image) == "function" then _image = opts.image end
  return Emerald
end

-- A require that never raises: returns the module or nil.
local function safeRequire(name)
  local req = _require or require
  local ok, value = pcall(req, name)
  if ok and type(value) == "table" then return value end
  return nil
end

